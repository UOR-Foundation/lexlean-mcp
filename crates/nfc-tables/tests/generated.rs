//! NF-02: the committed tables are a fresh generation from the pinned files.

mod common;

use common::{data, root, sha256_of};
use nfc_tables::tables::{
    check_exclusions, digest_token, halves, module, pack, sample, sample_closure, sample_seeds,
    sha256_hex, Packed, HEADER, SPLIT_AT,
};

#[test]
fn the_committed_tables_equal_a_fresh_generation_nf_02() {
    let packed = pack(&data()).expect("the tables pack");
    let (low, high) = halves(&packed.bytes);
    for (file, fresh) in [("nfc-tables-low.bin", low), ("nfc-tables-high.bin", high)] {
        let committed = std::fs::read(root().join("artifacts").join(file))
            .unwrap_or_else(|e| panic!("artifacts/{file}: {e}"));
        assert!(
            committed == fresh,
            "artifacts/{file} is not the generated byte string: run `cargo run -p nfc-tables --example generate_tables`"
        );
    }
    let sample = sample(&data(), &sample_seeds()).expect("the sample packs");
    let committed =
        std::fs::read(root().join("artifacts/nfc-sample.bin")).expect("artifacts/nfc-sample.bin");
    assert!(
        committed == sample.bytes,
        "artifacts/nfc-sample.bin is not the generated sample image: run `cargo run -p nfc-tables --example generate_tables`"
    );
    let source = std::fs::read_to_string(root().join("src/NfcTables.lex.tex"))
        .expect("src/NfcTables.lex.tex is committed");
    assert!(
        source == module(&packed, &sample),
        "src/NfcTables.lex.tex is not the generated module: run `cargo run -p nfc-tables --example generate_tables`"
    );
    assert!(
        !root().join("artifacts/nfc-tables.bin").exists(),
        "the one-piece byte string is not committed; the two halves are"
    );
}

#[test]
fn the_digests_are_the_same_in_the_artifacts_the_module_and_the_lock_nf_02() {
    let packed = pack(&data()).expect("the tables pack");
    let (low, high) = halves(&packed.bytes);
    let source = std::fs::read_to_string(root().join("src/NfcTables.lex.tex")).expect("reads");
    let config = std::fs::read_to_string(root().join("lexlean.toml")).expect("reads");
    let sample = sample(&data(), &sample_seeds()).expect("the sample packs");
    for (name, file, half) in [
        ("tablesLow", "nfc-tables-low.bin", low),
        ("tablesHigh", "nfc-tables-high.bin", high),
        ("sampleImage", "nfc-sample.bin", &sample.bytes[..]),
    ] {
        let digest = sha256_hex(half);
        assert_eq!(sha256_of(&root().join("artifacts").join(file)), digest);
        assert!(
            source.contains(&format!(
                "  name: {name},\n  type: Bytes,\n  length: {},\n  role: binary,\n  schema: bytes{{}},\n  sha256: {}\n",
                half.len(),
                digest_token(&digest)
            )),
            "the artifact declaration of {name} records another length or digest"
        );
        assert!(
            config.contains(&format!(
                "[[artifact_source]]\nsha256 = \"{digest}\"\npath = \"artifacts/{file}\"\n"
            )),
            "lexlean.toml pins another digest for {file}"
        );
    }
    assert_eq!(
        config.matches("[[artifact_source]]").count(),
        3,
        "the two halves of the tables and the sample image are the only artifacts"
    );
    assert_eq!(low.len(), SPLIT_AT, "the low half is SPLIT_AT octets");
    assert!(
        source.contains(&format!(
            "name: lowLength, parameters: [], result: Nat, body: {SPLIT_AT},"
        )),
        "the module records where the halves meet"
    );
}

#[test]
fn the_sections_are_contiguous_and_cover_the_byte_string_nf_02() {
    let packed = pack(&data()).expect("the tables pack");
    let mut end = HEADER;
    for section in [
        packed.ccc,
        packed.excluded,
        packed.single,
        packed.split,
        packed.pairs,
    ] {
        assert_eq!(section.start, end, "sections follow one another");
        end = section.start + section.count * section.width;
    }
    assert_eq!(end, packed.bytes.len(), "nothing follows the last section");
    assert_eq!(packed.split.count, packed.pairs.count);
}

#[test]
fn a_dropped_composition_exclusion_changes_the_tables_and_is_refused_by_the_cross_check_nf_02() {
    let mut other = data();
    let intact = pack(&other).expect("the tables pack").bytes;
    // U+0958 is a script-specific exclusion: listed in CompositionExclusions.txt
    // and in Full_Composition_Exclusion.
    let at = other
        .full_composition_exclusion
        .iter()
        .position(|&(first, last)| first <= 0x0958 && 0x0958 <= last)
        .expect("U+0958 is excluded");
    let (first, last) = other.full_composition_exclusion.remove(at);
    // Put back the rest of the range so exactly U+0958 is dropped.
    if first < 0x0958 {
        other.full_composition_exclusion.push((first, 0x0957));
    }
    if 0x0958 < last {
        other.full_composition_exclusion.push((0x0959, last));
    }
    other.full_composition_exclusion.sort_unstable();
    let error = check_exclusions(&other).expect_err("the cross-check sees the missing exclusion");
    assert!(
        error.0.contains("0958"),
        "the refusal names U+0958: {error}"
    );
    other.listed_exclusions.remove(&0x0958);
    let dropped = pack(&other).expect("the tables pack without the cross-check failing");
    assert_ne!(dropped.bytes, intact, "the generator reads the exclusions");
}

/// An independent reader of an image: the header, then the five tables.
struct Image {
    ccc: Vec<(u32, u32, u8)>,
    excluded: Vec<(u32, u32)>,
    single: Vec<(u32, u32)>,
    split: Vec<(u32, u32, u32)>,
    pairs: Vec<(u32, u32, u32)>,
}

fn be(bytes: &[u8], at: usize, width: usize) -> u32 {
    bytes[at..at + width]
        .iter()
        .fold(0, |acc, &b| (acc << 8) | u32::from(b))
}

fn read(packed: &Packed) -> Image {
    let bytes = &packed.bytes;
    let section = |k: usize| {
        (
            be(bytes, 6 * k, 3) as usize,
            be(bytes, 6 * k + 3, 3) as usize,
        )
    };
    let records = |k: usize, width: usize| {
        let (start, count) = section(k);
        (0..count)
            .map(move |i| start + i * width)
            .collect::<Vec<_>>()
    };
    Image {
        ccc: records(0, 7)
            .into_iter()
            .map(|at| (be(bytes, at, 3), be(bytes, at + 3, 3), bytes[at + 6]))
            .collect(),
        excluded: records(1, 6)
            .into_iter()
            .map(|at| (be(bytes, at, 3), be(bytes, at + 3, 3)))
            .collect(),
        single: records(2, 6)
            .into_iter()
            .map(|at| (be(bytes, at, 3), be(bytes, at + 3, 3)))
            .collect(),
        split: records(3, 9)
            .into_iter()
            .map(|at| (be(bytes, at, 3), be(bytes, at + 3, 3), be(bytes, at + 6, 3)))
            .collect(),
        pairs: records(4, 9)
            .into_iter()
            .map(|at| (be(bytes, at, 3), be(bytes, at + 3, 3), be(bytes, at + 6, 3)))
            .collect(),
    }
}

impl Image {
    fn class(&self, code: u32) -> u8 {
        self.ccc
            .iter()
            .find(|r| r.0 <= code && code <= r.1)
            .map_or(0, |r| r.2)
    }
    fn excluded(&self, code: u32) -> bool {
        self.excluded.iter().any(|r| r.0 <= code && code <= r.1)
    }
    fn single(&self, code: u32) -> Option<u32> {
        self.single.iter().find(|r| r.0 == code).map(|r| r.1)
    }
    fn split(&self, code: u32) -> Option<(u32, u32)> {
        self.split.iter().find(|r| r.0 == code).map(|r| (r.1, r.2))
    }
    fn pair(&self, first: u32, second: u32) -> Option<u32> {
        self.pairs
            .iter()
            .find(|r| r.0 == first && r.1 == second)
            .map(|r| r.2)
    }
}

#[test]
fn the_header_names_where_each_table_starts_and_how_many_records_it_has_nf_02() {
    let packed = pack(&data()).expect("the tables pack");
    for (k, section) in [
        packed.ccc,
        packed.excluded,
        packed.single,
        packed.split,
        packed.pairs,
    ]
    .iter()
    .enumerate()
    {
        assert_eq!(
            be(&packed.bytes, 6 * k, 3) as usize,
            section.start,
            "start of table {k}"
        );
        assert_eq!(
            be(&packed.bytes, 6 * k + 3, 3) as usize,
            section.count,
            "count of table {k}"
        );
    }
    let image = read(&packed);
    assert_eq!(
        image.pairs.len(),
        image.split.len(),
        "every two-part decomposition is a pair"
    );
    // The records are sorted by the key the binary search uses.
    assert!(image.ccc.windows(2).all(|w| w[0].0 < w[1].0));
    assert!(image.excluded.windows(2).all(|w| w[0].0 < w[1].0));
    assert!(image.single.windows(2).all(|w| w[0].0 < w[1].0));
    assert!(image.split.windows(2).all(|w| w[0].0 < w[1].0));
    assert!(image
        .pairs
        .windows(2)
        .all(|w| (w[0].0, w[0].1) < (w[1].0, w[1].1)));
}

#[test]
fn the_sample_answers_every_lookup_of_its_closure_as_the_full_tables_do_nf_11() {
    let data = data();
    let full = read(&pack(&data).expect("the tables pack"));
    let small = read(&sample(&data, &sample_seeds()).expect("the sample packs"));
    let closure = sample_closure(&data, &sample_seeds()).expect("the closure");
    assert!(
        closure.len() > 20 && closure.len() < 200,
        "{} code points",
        closure.len()
    );
    for &code in &closure {
        assert_eq!(small.class(code), full.class(code), "class of U+{code:04X}");
        assert_eq!(
            small.excluded(code),
            full.excluded(code),
            "exclusion of U+{code:04X}"
        );
        assert_eq!(
            small.single(code),
            full.single(code),
            "singleton of U+{code:04X}"
        );
        assert_eq!(
            small.split(code),
            full.split(code),
            "decomposition of U+{code:04X}"
        );
        for &second in &closure {
            assert_eq!(
                small.pair(code, second),
                full.pair(code, second),
                "pair U+{code:04X} U+{second:04X}"
            );
        }
    }
    // The closure is closed: the parts and the composites of its members belong to it.
    for &code in &closure {
        if let Some((first, second)) = full.split(code) {
            assert!(closure.contains(&first) && closure.contains(&second));
        }
        if let Some(target) = full.single(code) {
            assert!(closure.contains(&target));
        }
        for &second in &closure {
            if let Some(composite) = full.pair(code, second) {
                assert!(closure.contains(&composite));
            }
        }
    }
    assert!(
        small.pairs.len() < full.pairs.len() / 10,
        "the sample is a small subset"
    );
}
